// the frames g_0 ... g_n of a run whose step i is stepAt(i) (an integer step matrix), as compact enclosures (keep) and the final enclosure at precision P
function chunkedRun(stepAt,n,P,keep){
  let g={...stepIv(P).I};const frames=keep?[bfCompact(g,DRAW_BITS)]:null;
  for(let k=0;k<n;k+=CHUNK){let E=ONE_INT;const end=k+CHUNK<n?k+CHUNK:n;
    for(let t=k;t<end;t++){E=intMul(E,stepAt(t));if(frames)frames.push(bfCompact(bfMul(g,intToBf(E,P)),DRAW_BITS));}
    g=bfMul(g,intToBf(E,P));}
  return {g,frames};
}
